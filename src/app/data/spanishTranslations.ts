/**
 * Get Spanish translation for a key
 * Falls back to English (key) if not found
 */
export function getSpanishTranslation(key: string): string {
  return spanishTranslations[key] || key;
}

/**
 * Translate with parameters
 * Example: translateWithParams("result${count}", { count: 5 })
 */
export function translateWithParams(
  template: string,
  params: Record<string, string | number>
): string {
  let result = getSpanishTranslation(template);
  Object.entries(params).forEach(([key, value]) => {
    result = result.replace(`$${key}`, String(value));
  });
  return result;
}
